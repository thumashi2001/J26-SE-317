// Run from the backend folder:   node scripts/exportTopicLabels.js
// Writes frontend/src/utils/topicLabels.js so the website can show real topic names.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { TOPICS } from '../src/modules/c1/data/content/index.js';

const out = process.argv[2] || path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'frontend', 'src', 'utils', 'topicLabels.js');
const rows = Object.entries(TOPICS).map(([k, t]) => `  ${k}: { label: ${JSON.stringify(t.label)}, module: ${JSON.stringify(t.module_code)}, moduleName: ${JSON.stringify(t.module_name)}, lectures: ${JSON.stringify(t.lectures)}, semester: ${JSON.stringify(t.semester)} },`);
fs.writeFileSync(out, `// Generated by backend/scripts/exportTopicLabels.js from the question content. Do not edit by hand.\nexport const TOPIC_INFO = {\n${rows.join('\n')}\n};\n`);
console.log(`Wrote ${rows.length} topics to ${out}`);
