"""M19.7 — Authentic Question Topic Classification Batch Runner.

Processes authentic historical examination questions using trained M17 models
with conservative confidence-based abstention.
Preserves existing lecturer review decisions, excludes synthetic questions,
and produces standardized topic classification records.
"""

import argparse
import json
import sys
from pathlib import Path

# Ensure ai-services/c2 is on sys.path
BASE_DIR = Path(__file__).resolve().parents[1]
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

from services.batch_topic_classifier import BatchTopicClassifier
from services.m17_topic_prediction_service import M17TopicPredictionService
from services.question_classification_pipeline import QuestionClassificationPipeline
from services.question_classification_review_repository import QuestionClassificationReviewRepository
from services.topic_classification_validator import TopicClassificationValidator


def run_authentic_topic_classification(
    questions_path=None,
    output_path=None,
    threshold=0.38,
    dry_run=False,
):
    questions_file = Path(
        questions_path or BASE_DIR / "datasets" / "processed" / "questions.json"
    )
    output_file = Path(
        output_path or BASE_DIR / "datasets" / "processed" / "topic_classifications.json"
    )

    if not questions_file.exists():
        raise FileNotFoundError(f"Questions repository not found: {questions_file}")

    print(f"[M19.7] Loading authentic questions from: {questions_file}")
    pipeline = QuestionClassificationPipeline()
    questions = pipeline.load_questions(questions_file)

    # Initialize components
    from services.hybrid_topic_candidate_ranker import HybridTopicCandidateRanker
    predictor = M17TopicPredictionService(default_threshold=threshold)
    review_repo = QuestionClassificationReviewRepository()
    validator = TopicClassificationValidator()
    ranker = HybridTopicCandidateRanker(m17_predictor=predictor)

    batch_classifier = BatchTopicClassifier(
        classifier=predictor,
        validator=validator,
        review_repository=review_repo,
        default_threshold=threshold,
        authentic_only=True,
        ranker=ranker,
    )

    prepared = pipeline.prepare_questions(questions)
    batch_result = batch_classifier.classify_questions(prepared)
    summary = batch_result["summary"]

    output_document = {
        "schema_version": "1.0",
        "source_repository": str(questions_file),
        "classification_metadata": {
            "model_family": "M17_scikit_learn",
            "abstention_threshold": threshold,
            "abstention_policy": "conservative",
            "training_source": "synthetic_development_data",
            "provisional_disclaimer": (
                "Provisional topic classifications generated by synthetic-trained M17 models. "
                "Requires academic lecturer review before inclusion in verified historical evidence."
            ),
        },
        "summary": summary,
        "results": batch_result["results"],
    }

    if not dry_run:
        output_file.parent.mkdir(parents=True, exist_ok=True)
        with output_file.open("w", encoding="utf-8") as f:
            json.dump(output_document, f, indent=2, ensure_ascii=False)
        print(f"[M19.7] Successfully saved topic classifications to: {output_file}")
    else:
        print(f"[M19.7] Dry-run complete. Output not saved.")

    print("\n" + "=" * 60)
    print("M19.7 AUTHENTIC TOPIC CLASSIFICATION SUMMARY")
    print("=" * 60)
    print(f"Total questions in input:       {summary['total_questions']}")
    print(f"Authentic questions processed:  {summary['authentic_processed']}")
    print(f"Synthetic questions excluded:   {summary['synthetic_excluded']}")
    print(f"Provisionally classified:       {summary['classified']}")
    print(f"Abstained / unclassified:       {summary['unclassified']}")
    print(f"  - Abstained below threshold:  {summary['abstained']}")
    print(f"  - Empty text / skipped:       {summary['empty_text']}")
    print(f"Lecturer-verified:              {summary['lecturer_verified']}")
    print(f"Lecturer-rejected:              {summary['lecturer_rejected']}")
    print(f"Invalid / validation errors:    {summary['invalid']}")
    print("=" * 60)

    return output_document


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="M19.7 Batch Authentic Question Topic Classification"
    )
    parser.add_argument(
        "--questions",
        type=str,
        default=None,
        help="Path to questions.json repository",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Path to topic_classifications.json",
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=0.38,
        help="M17 conservative abstention threshold (default: 0.38)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Simulate classification without writing to disk",
    )
    args = parser.parse_args()

    run_authentic_topic_classification(
        questions_path=args.questions,
        output_path=args.output,
        threshold=args.threshold,
        dry_run=args.dry_run,
    )
