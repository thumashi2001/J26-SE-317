"""DATASET_CARD.md for the repaired dataset. Every number is read from manifest.json / validation_report.json /
metrics_report.json at render time; nothing is typed by hand."""

from __future__ import annotations

from typing import Any


def _kv_table(d: dict[str, Any], key_head: str, val_head: str) -> list[str]:
    """Two-column Markdown table from a dictionary."""
    lines = [f"| {key_head} | {val_head} |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in d.items()]
    return lines


def render_card(manifest: dict[str, Any], report: dict[str, Any] | None, metrics: dict[str, Any] | None) -> str:
    """Build the dataset card (counts, repairs, validation and metrics) as Markdown."""
    c = manifest["counts"]
    o, r = c["original"], c["repaired"]
    acc = manifest["accounting"]
    lines = [
        f"# Dataset card - {manifest['dataset_version']}",
        "",
        f"Repaired from `{manifest['source_dataset_version']}` (scope of this build: **{manifest['scope']}**). "
        "Generated by `datasets/repair_c3_dataset.py` from `manifest.json`; the numbers below are not hand-typed.",
        "",
        "No question or answer was generated or reworded. A value is repaired only when the data, the rubric or a "
        "documented rule proves it; otherwise the record is quarantined or flagged. Splits are exactly as in the "
        "original. Synthetic controlled data, not authentic student responses; no expert validation exists.",
        "",
        "## Counts",
        "",
        *_kv_table({
            "original questions": o["questions"], "original answers": o["answers"],
            "original rubric rows": o["rubric_rows"],
            "eligible questions": r["eligible_questions"], "ineligible questions": r["ineligible_questions"],
            "eligible answers (primary set)": r["eligible_answers"],
            "quarantined answers": r["quarantined_answers"],
            "repaired ineligible controls": r["repaired_ineligible_controls"],
            "review queue": r["review_queue"],
        }, "item", "count"),
        "",
        "### Accounting (every original answer appears in exactly one place)",
        "",
        "| group | original | eligible | quarantined | repaired ineligible controls |",
        "|---|---|---|---|---|",
    ]
    for g, a in acc.items():
        lines.append(f"| {g} | {a['original_answers']} | {a['eligible']} | {a['quarantined']} | "
                     f"{a['repaired_ineligible_controls']} |")
    lines += [
        "",
        "### Eligible set per split",
        "",
        "| split | eligible questions | eligible answers | original answers |",
        "|---|---|---|---|",
    ]
    for s in ("train", "validation", "test"):
        lines.append(f"| {s} | {r['eligible_questions_by_split'].get(s, 0)} | {r['eligible_by_split'].get(s, 0)} | "
                     f"{o['by_split_answers'].get(s, 0)} |")
    lines += ["", "### Label distribution (answers)", "", "| label | original | eligible |", "|---|---|---|"]
    for lab in o["label_distribution"]:
        lines.append(f"| {lab} | {o['label_distribution'][lab]} | {r['eligible_label_distribution'].get(lab, 0)} |")
    lines += ["", "### Quarantine reasons", "", *_kv_table(r["quarantine_by_reason"], "reason", "answers"),
              "", "## Repair ledger (repair_manifest.csv)", "",
              *_kv_table(manifest["ledger"]["by_status"], "status", "rows"), "",
              *_kv_table(manifest["ledger"]["by_category"], "issue category", "rows"), "",
              "## Flags and limitations (from the build)", "",
              f"- Criterion-id map: {r['criterion_map_resolved']} resolved, {r['criterion_map_unresolved']} "
              f"unresolved; of the resolved ids {r['criterion_map_marks_agree_true']} have the same mark as the "
              f"answer criterion and {r['criterion_map_marks_agree_false']} do not (the rubric file holds one "
              "question-level row, so an id match is not a semantic match). Rubric criterion descriptions are "
              "unrecoverable and were not invented.",
              f"- Template negative controls kept in the eligible set: {r['template_negative_controls_eligible']} "
              "(constant IRRELEVANT string; never moved between splits).",
              f"- Placeholder-concept answers in the eligible set: {r['placeholder_flagged_eligible']}.",
              f"- Questions flagged `scope_review`: {r['scope_review_questions']} "
              f"({', '.join(manifest['decisions']['scope_review_questions'])}); kept eligible, a human decides.",
              f"- Rubric rows re-keyed to `SYN-REPL-*`: {r['rubric_rows_rekeyed']} (they still carry the allocation of "
              "the replaced original question, which does not sum to the 10 marks of the replacement).",
              "- `reference_answer` in the answers file is empty and question-bank references are generic templates.",
              "- Replacement questions are ineligible: only a zero-mark negative control survives per question.",
              f"- The original claimed qa = {manifest['original_manifest_claims'].get('qa')!r}; this build reports the "
              "real validation result below.",
              ""]
    if report is not None:
        lines += ["## Validation (validation_report.json)", "", "| check | hard | status | value |", "|---|---|---|---|"]
        for ck in report["checks"]:
            lines.append(f"| {ck['name']} | {ck['hard']} | {ck['status'].upper()} | {ck.get('summary', '')} |")
        lines += ["", f"Overall: **{report['overall']}** (hard failures: "
                  f"{', '.join(report['hard_failures']) or 'none'})", ""]
    if metrics is not None:
        lines += ["## Recomputed metrics (metrics_report.json)", "", metrics.get("table_md", ""), ""]
    return "\n".join(lines) + "\n"
