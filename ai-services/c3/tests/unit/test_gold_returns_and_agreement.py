def test_question_bootstrap_is_deterministic_and_resamples_questions():
    rows = [{"question": f"q{i % 6}", "v": float(i % 3)} for i in range(60)]
    stat = lambda rs: sum(r["v"] for r in rs) / len(rs) if rs else None  # noqa: E731
    a, b = agreement.question_bootstrap(rows, stat, 200, "seed"), agreement.question_bootstrap(rows, stat, 200, "seed")
    assert a == b and a["ci"][0] <= a["estimate"] <= a["ci"][1] and a["questions"] == 6
    assert agreement.question_bootstrap(rows[:5] and [{**r, "question": "only"} for r in rows], stat, 50, "s")["ci"] is None


