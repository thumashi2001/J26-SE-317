@pytest.fixture()
def study(tmp_path):
    """Two toy markers on one toy sheet set: marker 1 chooses by item hash, marker 2 differs on every third item."""
    toy = build_toy_dataset(tmp_path / "data")
    plan = sampling.plan(toy, seed="s", pilot_seed="p")
    built = sheets.build_sheets(toy, plan, "final", toy_rubrics(plan, "final"), MARKERS, SALT, "toy_fixture")
    sa, sb = built["sheets"]["m1"], built["sheets"]["m2"]
    ra = fill_return(sa, lambda idx, item, c, ids: by_item_hash(item["item_id"], ids))
    rb = disagree_on_some(fill_return(sb, lambda idx, item, c, ids: by_item_hash(item["item_id"], ids)), sb)
    return {"sa": sa, "sb": sb, "ra": ra, "rb": rb, "built": built}


