@pytest.mark.parametrize("k, seed", [(3, 1), (4, 2), (5, 3)])
def test_weighted_kappa_matches_scikit_learn(k, seed):
    rng = random.Random(seed)
    a = [rng.randrange(k) for _ in range(60)]
    b = [min(k - 1, max(0, x + rng.choice([-1, 0, 0, 1]))) for x in a]
    assert agreement.weighted_kappa(a, b, k) == pytest.approx(cohen_kappa_score(a, b, weights="quadratic", labels=list(range(k))))


def test_weighted_kappa_edge_cases():
    assert agreement.weighted_kappa([0, 1, 2, 1], [0, 1, 2, 1], 3) == pytest.approx(1.0)
    assert agreement.weighted_kappa([0, 0, 0], [0, 0, 0], 3) is None  # no variation, undefined
    assert agreement.weighted_kappa([], [], 3) is None
    assert agreement.weighted_kappa([0, 1, 2, 0], [2, 1, 0, 2], 3) < 0


def test_icc_matches_the_shrout_and_fleiss_worked_example():
    ratings = [[9, 2, 5, 8], [6, 1, 3, 2], [8, 4, 6, 8], [7, 1, 2, 6], [10, 5, 6, 9], [6, 2, 4, 7]]
    assert agreement.icc(ratings, "1,1") == pytest.approx(0.17, abs=0.005)
    assert agreement.icc(ratings, "2,1") == pytest.approx(0.29, abs=0.005)
    assert agreement.icc(ratings, "3,1") == pytest.approx(0.71, abs=0.005)
    assert agreement.icc([[1, 1], [2, 2], [3, 3]], "2,1") == pytest.approx(1.0)
    assert agreement.icc([[1.0, 2.0]], "2,1") is None
    with pytest.raises(GoldToolError):
        agreement.icc(ratings, "4,1")


def _brute_force_alpha(units, k):
    """Krippendorff's alpha (ordinal) straight from the definition over all pairs of pairable values."""
    values = [[v for v in u if v is not None] for u in units]
    values = [u for u in values if len(u) >= 2]
    n_c = [0.0] * k
    for u in values:
        for v in u:
            n_c[v] += 1.0
    n = sum(n_c)

    def delta2(c, d):
        lo, hi = min(c, d), max(c, d)
        return (sum(n_c[lo:hi + 1]) - (n_c[c] + n_c[d]) / 2.0) ** 2

    do = sum(delta2(u[i], u[j]) / (len(u) - 1) for u in values for i in range(len(u)) for j in range(len(u)) if i != j) / n
    pool = [v for u in values for v in u]
    de = sum(delta2(pool[i], pool[j]) for i in range(len(pool)) for j in range(len(pool)) if i != j) / (n * (n - 1))
    return None if de == 0 else 1 - do / de


def test_alpha_matches_a_brute_force_reference_including_missing_values():
    rng = random.Random(7)
    units = [[rng.randrange(4) if rng.random() > 0.15 else None for _ in range(3)] for _ in range(40)]
    assert agreement.krippendorff_alpha_ordinal(units, 4) == pytest.approx(_brute_force_alpha(units, 4))
    pairs = [[rng.randrange(3), rng.randrange(3)] for _ in range(50)]
    assert agreement.krippendorff_alpha_ordinal(pairs, 3) == pytest.approx(_brute_force_alpha(pairs, 3))
    assert agreement.krippendorff_alpha_ordinal([[0, 1], [1, 2], [2, 2], [0, 0]], 3) == pytest.approx(
        _brute_force_alpha([[0, 1], [1, 2], [2, 2], [0, 0]], 3))
    assert agreement.krippendorff_alpha_ordinal([[0, 0], [1, 1], [2, 2]], 3) == pytest.approx(1.0)
    assert agreement.krippendorff_alpha_ordinal([[1, 1], [1, 1]], 3) is None  # no variation
    assert agreement.krippendorff_alpha_ordinal([[1, None]], 3) is None


def test_statistics_reject_invalid_inputs_instead_of_guessing():
    with pytest.raises(GoldToolError, match="different lengths"):
        agreement.weighted_kappa([0, 1], [0], 3)
    with pytest.raises(GoldToolError, match="different lengths"):
        agreement.exact_agreement([1, 2], [1])
    with pytest.raises(GoldToolError, match="different lengths"):
        agreement.mean_abs_difference([1.0], [1.0, 2.0])
    for bad in ([0, 3], [-1, 0], [0.5, 1], [True, 1]):
        with pytest.raises(GoldToolError, match="every rank"):
            agreement.weighted_kappa(bad, [0, 1], 3)
    with pytest.raises(GoldToolError, match="every rank"):
        agreement.krippendorff_alpha_ordinal([[0, 5]], 3)
    with pytest.raises(GoldToolError, match="complete"):
        agreement.icc([[1, 2], [3]], "2,1")


def test_small_and_degenerate_samples_give_none_not_a_number():
    assert agreement.weighted_kappa([1], [1], 3) is None  # one pair, no variation
    assert agreement.krippendorff_alpha_ordinal([], 3) is None
    assert agreement.krippendorff_alpha_ordinal([[None, None], [2, None]], 3) is None  # nothing pairable
    assert agreement.icc([], "2,1") is None and agreement.icc([[1, 2]], "2,1") is None
    assert agreement.icc([[1, 2], [1, 2]], "2,1") == pytest.approx(0.0)  # identical subjects: no between-subject variance
    assert agreement.exact_agreement([], []) is None and agreement.mean_abs_difference([], []) is None


